/// Kind of recording (`recordings.kind`).
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum RecordingKind {
    /// A clip saved from the replay buffer.
    Clip,
    /// One part of a continuous session recording.
    Session,
}

impl RecordingKind {
    /// Database spelling.
    pub fn as_str(self) -> &'static str {
        match self {
            RecordingKind::Clip => "clip",
            RecordingKind::Session => "session",
        }
    }

    fn parse(s: &str) -> Option<Self> {
        match s {
            "clip" => Some(RecordingKind::Clip),
            "session" => Some(RecordingKind::Session),
            _ => None,
        }
    }
}

/// Lifecycle status of a recording row (`recordings.status`).
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum RecStatus {
    /// File is still being written.
    Recording,
    /// Complete on disk, not yet probed.
    Pending,
    /// Probed and playable.
    Ready,
    /// File no longer found under its root.
    Missing,
    /// Writing or probing failed.
    Error,
}

impl RecStatus {
    /// Database spelling.
    pub fn as_str(self) -> &'static str {
        match self {
            RecStatus::Recording => "recording",
            RecStatus::Pending => "pending",
            RecStatus::Ready => "ready",
            RecStatus::Missing => "missing",
            RecStatus::Error => "error",
        }
    }

    fn parse(s: &str) -> Option<Self> {
        match s {
            "recording" => Some(RecStatus::Recording),
            "pending" => Some(RecStatus::Pending),
            "ready" => Some(RecStatus::Ready),
            "missing" => Some(RecStatus::Missing),
            "error" => Some(RecStatus::Error),
            _ => None,
        }
    }
}

/// Where a recording came from (`recordings.source`).
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum RecordingSource {
    /// Written by the recorder. The default.
    #[default]
    Recorded,
    /// Copied in from another folder by the import tool.
    Import,
    /// Indexed in place from an extra library folder.
    External,
}

impl RecordingSource {
    /// Database spelling.
    pub fn as_str(self) -> &'static str {
        match self {
            RecordingSource::Recorded => "recorded",
            RecordingSource::Import => "import",
            RecordingSource::External => "external",
        }
    }

    fn parse(s: &str) -> Option<Self> {
        match s {
            "recorded" => Some(RecordingSource::Recorded),
            "import" => Some(RecordingSource::Import),
            "external" => Some(RecordingSource::External),
            _ => None,
        }
    }
}

/// Input for [`Library::insert_recording`]. Timestamps are UTC milliseconds.
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
pub struct NewRecording {
    /// ULID (26 characters), generated by the caller.
    pub id: String,
    /// Clip or session part.
    pub kind: RecordingKind,
    /// Session ULID for session parts; `None` for clips.
    pub session_id: Option<String>,
    /// 1-based part index within the session.
    pub part_index: Option<i64>,
    /// Canonical game id, or `None` for the unknown-game bucket.
    pub game_id: Option<String>,
    /// Owning storage root (`storage_roots.id`).
    pub root_id: i64,
    /// Path relative to the root, `\` or `/` separated as stored by the caller.
    pub rel_path: String,
    /// Last path segment, including extension.
    pub file_name: String,
    /// `mp4` or `mkv`.
    pub ext: String,
    /// File size in bytes.
    pub size_bytes: i64,
    /// Last-known file mtime (ms).
    pub file_mtime_ms: i64,
    /// Recording start time (ms).
    pub created_at_ms: i64,
    /// Row insert time (ms).
    pub added_at_ms: i64,
    /// Duration in ms; 0 if not yet probed.
    pub duration_ms: i64,
    /// Initial status.
    pub status: RecStatus,
    /// Error detail when `status` is `Error`.
    pub error_detail: Option<String>,
    /// Serialized session `EndReason`, if any.
    pub end_reason: Option<String>,
    /// True if the part was recovered after a crash.
    pub recovered: bool,
    /// True if queue overflow occurred while recording.
    pub degraded: bool,
    /// Packets dropped by overflow or pre-keyframe discard.
    pub dropped_packets: i64,
    /// Non-recorded time inside the part, in ms.
    pub gap_ms: i64,
    /// True if the file is still fragmented (faststart remux skipped or failed).
    pub needs_faststart: bool,
}

